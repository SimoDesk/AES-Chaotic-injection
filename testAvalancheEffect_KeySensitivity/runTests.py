import random
import secrets
import subprocess
import os
import csv

from enum import Enum

current_dir = os.path.dirname(os.path.abspath(__file__))

maps = ["standard",'logistic','tent','henon','arnold','sine','chebyshev','lorenz','chen','rossler']

avalanche_csv = "avalancheEffect_results.csv"
key_sensitivity_csv = "keySensitivity_results.csv"

TESTS_NUMBER = 10000

class TestType(Enum):
    AVALANCHE_EFFECT = 1
    KEY_SENSITIVITY = 2

# Define a function to calculate the avalanche effect between two ciphertext files
def calcola_hamming(file_c1, file_c2):
    # store in two variables the bytes read from the two ciphertext files, which are opened in binary mode
    with open(file_c1, 'rb') as f1, open(file_c2, 'rb') as f2:
        c1_bytes = f1.read()
        c2_bytes = f2.read()

    # Calculate the Hamming distance between the two ciphertexts by counting the number of differing bits
    distanza_hamming = sum(bin(b1 ^ b2).count('1') for b1, b2 in zip(c1_bytes, c2_bytes))

    # Calculate the percentage of differing bits relative to the total number of bits (128 bits for AES)
    percentuale = (distanza_hamming / 128.0) * 100
    
    return distanza_hamming, percentuale


# Define a function to run the key sensitivity test
def run_key_sensitivity(plaintext_hex, iv_hex, key_hex, map_output_dir, map):
    # Run the test_avalanche executable with the original plaintext
    subprocess.run(["./test_avalanche_keySens", map, plaintext_hex, iv_hex, key_hex, str(0)], capture_output=True, text=True)

    # transform the key hex string into a bytearray to flip a random bit
    byte_array = bytearray(bytes.fromhex(key_hex))

    # select a random byte and a random bit within that byte to flip
    random_byte_id = random.randint(0, len(byte_array) - 1)
    random_bit_id = random.randint(0, 7)

    # flip the selected bit in the selected byte by using XOR operation 
    byte_array[random_byte_id] ^= (1 << random_bit_id)

    # convert the modified bytearray back to a hex string
    modified_key_hex = byte_array.hex()

    # Run the test_avalanche executable with the modified key
    subprocess.run(["./test_avalanche_keySens", map, plaintext_hex, iv_hex, modified_key_hex, str(1)], capture_output=True, text=True)

    # Calculate the avalanche effect between the two ciphertexts generated by the original and modified plaintexts
    file_c1 = os.path.join(map_output_dir, "cipher_0.bin")
    file_c2 = os.path.join(map_output_dir, "cipher_1.bin")
    distanza_hamming, percentuale = calcola_hamming(file_c1, file_c2)

    return distanza_hamming, percentuale


# Define a function to run the avalanche effect test
def run_avalanche_effect(plaintext_hex, iv_hex, key_hex, map_output_dir, map):
    # Run the test_avalanche executable with the original plaintext
    subprocess.run(["./test_avalanche_keySens", map, plaintext_hex, iv_hex, key_hex, str(0)], capture_output=True, text=True)

    # transform the plaintext hex string into a bytearray to flip a random bit
    byte_array = bytearray(bytes.fromhex(plaintext_hex))

    # select a random byte and a random bit within that byte to flip
    random_byte_id = random.randint(0, len(byte_array) - 1)
    random_bit_id = random.randint(0, 7)

    # flip the selected bit in the selected byte by using XOR operation 
    byte_array[random_byte_id] ^= (1 << random_bit_id)

    # convert the modified bytearray back to a hex string
    modified_plaintext_hex = byte_array.hex()

    # Run the test_avalanche executable with the modified plaintext
    subprocess.run(["./test_avalanche_keySens", map, modified_plaintext_hex, iv_hex, key_hex, str(1)], capture_output=True, text=True)

    # Calculate the avalanche effect between the two ciphertexts generated by the original and modified plaintexts
    file_c1 = os.path.join(map_output_dir, "cipher_0.bin")
    file_c2 = os.path.join(map_output_dir, "cipher_1.bin")
    distanza_hamming, percentuale = calcola_hamming(file_c1, file_c2)

    return distanza_hamming, percentuale


# Define a function to run the tests for either avalanche effect or key sensitivity
def run_test(test_type):
    if test_type == TestType.AVALANCHE_EFFECT:
        file = open(avalanche_csv, mode='w', newline='')
        writer = csv.writer(file)
    elif test_type == TestType.KEY_SENSITIVITY:
        file = open(key_sensitivity_csv, mode='w', newline='')
        writer = csv.writer(file)
        
    writer.writerow(["Mappa", "Average Hamming Distance", "Distance from perfection", "Average of Differing Bits (%)"])

    for map in maps:

        total_distanza_hamming = 0
        total_percentuale = 0

        # Create the output directory for the current map if it doesn't exist
        map_output_dir = os.path.join(current_dir, "ciphers", map)
        os.makedirs(map_output_dir, exist_ok=True)

        for _ in range(TESTS_NUMBER):
            # Generate random plaintext, IV, and key
            plaintext_hex = secrets.token_hex(16)  # 16 bytes = 32 hex characters
            iv_hex = secrets.token_hex(12)         # 12 bytes = 24 hex characters
            key_hex = secrets.token_hex(32)        # 32 bytes = 64 hex characters

            if test_type == TestType.AVALANCHE_EFFECT:
                distanza_hamming, percentuale = run_avalanche_effect(plaintext_hex, iv_hex, key_hex, map_output_dir, map)
            elif test_type == TestType.KEY_SENSITIVITY:
                distanza_hamming, percentuale = run_key_sensitivity(plaintext_hex, iv_hex, key_hex, map_output_dir, map)

            total_distanza_hamming += distanza_hamming
            total_percentuale += percentuale

        print(f"Completed {test_type} tests for map: {map}.")

        # Calculate the average Hamming distance and percentage of differing bits over all tests
        avg_distanza_hamming = total_distanza_hamming / TESTS_NUMBER
        avg_percentuale = total_percentuale / TESTS_NUMBER


        # Calculate the absolute difference from the ideal Hamming distance of 64
        absolute_difference = abs(avg_distanza_hamming - 64)

        # Format the numbers to 4 decimal places and replace the dot with a comma
        avg_dist_str = f"{avg_distanza_hamming:.4f}".replace('.', ',')
        avg_perc_str = f"{avg_percentuale:.4f}".replace('.', ',')
        abs_diff_str = f"{absolute_difference:.4f}".replace('.', ',')
        
        # Write the results to the CSV file
        writer.writerow([map, avg_dist_str, abs_diff_str, avg_perc_str])


if __name__ == "__main__":
    subprocess.run(["make", "clear"])  # Clean previous builds and outputs
    subprocess.run(["make", "build"])  # Ensure the executable is built before running the test

    # Run the avalanche effect test
    run_test(TestType.AVALANCHE_EFFECT)
    run_test(TestType.KEY_SENSITIVITY)