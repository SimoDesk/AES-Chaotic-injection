import networkx as nx
import matplotlib.pyplot as plt

# Function to extract function memory usage from a line in the .su file
def getFunctionMemoryUsage(line):
    parts = line.split('\t')
    funPath = parts[0].split(':')

    return funPath[-1], parts[1]

# Function to extract edge information from a line in the .ci file
def getEdge(line):
    clean = line.replace('{', '').replace('}', '').replace('"', '')
    parts = clean.split(' ')

    n2Parts = parts[5].split(':')

    if len(n2Parts) == 2:
        return parts[3], n2Parts[1]
    else:
        return parts[3], n2Parts[0]

# Function to calculate the maximum memory usage along all paths from a given method to any leaf node in the graph
def getMaxMemory(method, G):
    leaves = [node for node in G.nodes() if G.out_degree(node) == 0]

    maxMem = 0

    for f in leaves:
        for path in nx.all_simple_paths(G, source=method, target=f):
            currMem = sum(int(G.nodes[n].get('memory', 0)) for n in path)

            if currMem > maxMem:
                maxMem = currMem

    return maxMem


