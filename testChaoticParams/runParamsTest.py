# Define a worker function to be executed in parallel for each test
def worker(test_type, map_obj, alfa, beta, delta):
    # Generate random plaintext, IV, and key
    plaintext_hex = secrets.token_hex(16)  # 16 bytes = 32 hex characters
    iv_hex = secrets.token_hex(12)         # 12 bytes = 24 hex characters
    key_hex = secrets.token_hex(32)        # 32 bytes = 64 hex characters

    if test_type == TestType.AVALANCHE_EFFECT:
        return run_avalanche_effect(plaintext_hex, iv_hex, key_hex, map_obj, alfa, beta, delta)
    elif test_type == TestType.KEY_SENSITIVITY:
        return run_key_sensitivity(plaintext_hex, iv_hex, key_hex, map_obj, alfa, beta, delta)

    return 0, 0  # Default return values in case of an unexpected test type

# Define a function to run the tests for either avalanche effect or key sensitivity
def load_phase_two_pairs(ranking_path, top_n):
    # Load the top N pairs of (alfa, beta) for each map from the ranking CSV file.
    if not os.path.isfile(ranking_path):
        raise FileNotFoundError(
            f"Ranking CSV not found: {ranking_path}. Run phase 1 first."
        )

    selected = {map_name: [] for map_name in maps}
    with open(ranking_path, newline="") as ranking_file:
        reader = csv.DictReader(ranking_file, delimiter=";")
        required = {"Mappa", "Rank", "alfa", "beta"}
        missing = required.difference(reader.fieldnames or [])
        if missing:
            raise ValueError(
                f"Ranking CSV is missing columns: {', '.join(sorted(missing))}"
            )

        rows = []
        for row in reader:
            map_name = row["Mappa"].strip()
            if map_name not in selected:
                continue
            rows.append((
                map_name,
                int(row["Rank"]),
                float(row["alfa"].replace(",", ".")),
                float(row["beta"].replace(",", ".")),
            ))

    for map_name, rank, alpha, beta_value in sorted(rows, key=lambda item: item[1]):
        if rank <= top_n and len(selected[map_name]) < top_n:
            selected[map_name].append((alpha, beta_value))

    missing_maps = [map_name for map_name, pairs in selected.items() if not pairs]
    if missing_maps:
        raise ValueError(
            f"Ranking CSV has no candidates for: {', '.join(missing_maps)}"
        )
    return selected


def run_test(test_type, alfa, beta, delta, tests_number, stability_data,
             map_name=None):

    if test_type == TestType.AVALANCHE_EFFECT:
        mode = 'a' if os.path.exists(avalanche_csv) else 'w'
    elif test_type == TestType.KEY_SENSITIVITY:
        mode = 'a' if os.path.exists(key_sensitivity_csv) else 'w'

    if test_type == TestType.AVALANCHE_EFFECT:
        file = open(avalanche_csv, mode=mode, newline='')
        writer = csv.writer(file)
    elif test_type == TestType.KEY_SENSITIVITY:
        file = open(key_sensitivity_csv, mode=mode, newline='')
        writer = csv.writer(file)

    if mode == 'w':
        writer.writerow(["Mappa", "alfa", "beta", "Average Hamming Distance", "Distance from perfection", "Average of Differing Bits (%)"])

    test_maps = [map_name] if map_name is not None else maps
    for map in test_maps:

        total_distanza_hamming = 0
        total_percentuale = 0

        # Create the output directory for the current map if it doesn't exist
        map_output_dir = os.path.join(current_dir, "ciphers", map)
        os.makedirs(map_output_dir, exist_ok=True)

        # Determine the number of workers based on SLURM_CPUS_ON_NODE or the number of CPU cores
        slurm_cups = os.environ.get('SLURM_CPUS_ON_NODE')
        max_workers_count = int(slurm_cups) if slurm_cups else min(8, multiprocessing.cpu_count())

        # Use a ProcessPoolExecutor to run the tests in parallel
        with concurrent.futures.ProcessPoolExecutor(max_workers=max_workers_count) as executor:

            # Submit the worker function for each test to the executor and collect the futures
            futures = [executor.submit(worker, test_type, map, alfa, beta, delta)
                       for _ in range(tests_number)]

            # Wait for the futures to complete and collect the results
            for future in concurrent.futures.as_completed(futures):
                try:
                    distanza_hamming, percentuale = future.result()

                    total_distanza_hamming += distanza_hamming
                    total_percentuale += percentuale
                    
                except Exception as e:
                    print(f"An error occurred during test execution: {e}")

        print(f"Completed {test_type} tests for map: {map}.")

        # Calculate the average Hamming distance and percentage of differing bits over all tests
        avg_distanza_hamming = total_distanza_hamming / tests_number
        avg_percentuale = total_percentuale / tests_number


        # Calculate the absolute difference from the ideal Hamming distance of 64
        absolute_difference = abs(avg_distanza_hamming - 64)

        # Format the numbers to 4 decimal places and replace the dot with a comma
        avg_dist_str = f"{avg_distanza_hamming:.4f}".replace('.', ',')
        avg_perc_str = f"{avg_percentuale:.4f}".replace('.', ',')
        abs_diff_str = f"{absolute_difference:.4f}".replace('.', ',')
        
        # Write the results to the CSV file
        writer.writerow([map, alfa, beta, avg_dist_str, abs_diff_str, avg_perc_str])

        if test_type == TestType.AVALANCHE_EFFECT:
            min_w, max_w, w_max, measured_delta, saturated, non_finite = stability_data
            unstable = int(float(w_max) > 100.0)
            stability_exists = os.path.exists(stability_csv)
            with open(stability_csv, "a", newline="") as stability_file:
                stability_writer = csv.writer(stability_file)
                if not stability_exists:
                    stability_writer.writerow([
                        "Mappa", "alfa", "beta", "W min", "W max", "W max abs",
                        "delta",
                        "Saturated samples", "Non-finite samples",
                        "Unstable samples",
                        "Stability samples"
                    ])
                stability_writer.writerow([
                    map, alfa, beta, min_w, max_w, w_max, measured_delta,
                    saturated, non_finite, unstable,
                    STABILITY_ITERATIONS
                ])

    file.close()

# Run the stability measurement for a given map and (alfa, beta) pair using the measure_stability executable.
def measure_stability(map_name, alpha, beta):
    result = subprocess.run([os.path.join(current_dir, "measure_stability"), map_name, str(alpha), str(beta)], capture_output=True, text=True, check=True)
    return result.stdout.strip().split(",")

# Define a function to configure the output files for a given phase of testing.
def configure_output_files(phase):
    # Create a directory for the current phase of testing and set the global CSV file paths for avalanche effect, key sensitivity, and stability results.
    global avalanche_csv, key_sensitivity_csv, stability_csv

    # Create a directory for the current phase of testing and set the global CSV file paths for avalanche effect, key sensitivity, and stability results.
    phase_dir = os.path.join(RESULTS_DIR, f"phase_{phase}")
    os.makedirs(phase_dir, exist_ok=True)

    # Set the global CSV file paths for avalanche effect, key sensitivity, and stability results to be within the phase directory.
    avalanche_csv = os.path.join(phase_dir, "avalancheEffect_results.csv")
    key_sensitivity_csv = os.path.join(phase_dir, "keySensitivity_results.csv")
    stability_csv = os.path.join(phase_dir, "stability_results.csv")
    
    return phase_dir

# Define a function to clear the results of a specific phase before running new tests.
def clear_phase_results(phase):
    phase_dir = os.path.join(RESULTS_DIR, f"phase_{phase}")
    if os.path.isdir(phase_dir):
        shutil.rmtree(phase_dir)


def main():
    # Parse command-line arguments to determine which phase of testing to run, the number of tests, the number of top pairs to consider, and the ranking CSV file to use.
    parser = argparse.ArgumentParser(
        description="Run phase 1 screening or phase 2 confirmation tests."
    )
    parser.add_argument(
        "--phase", choices=("1", "2", "all"), default="all",
        help="1: screening; 2: confirmation; all: esegue entrambe le fasi."
    )
    parser.add_argument(
        "--tests", type=int, default=None,
        help="Numero di test per metrica e coppia."
    )
    parser.add_argument(
        "--top", type=int, default=5,
        help="Number of ranked pairs per map in phase 2 (default: 5)."
    )
    parser.add_argument(
        "--ranking", default=RANKING_CSV,
        help="Ranking CSV generated by getLeaderBoard.py."
    )
    args = parser.parse_args()
    if args.tests is not None and args.tests <= 0:
        parser.error("--tests must be positive")
    if args.top <= 0:
        parser.error("--top must be positive")

    phase = args.phase

    # =============================================================================================================================================================================

    # inner function to execute a specific phase of testing, given the phase number, pairs of (alfa, beta) for each map, and the number of tests to run.
    def execute_phase(phase_number, pairs_by_map, tests_number):

        # Execute the tests for the given phase, pairs of (alfa, beta), and number of tests.
        phase_dir = configure_output_files(2 if phase_number == 2 else 1)

        # Set the global paths for the CSV files containing the test results for avalanche effect and key sensitivity used to the createPlots function.
        createPlots.__globals__["TEST_FILES"] = {
            "Avalanche effect": os.path.join(phase_dir, "avalancheEffect_results.csv"),
            "Key sensitivity": os.path.join(phase_dir, "keySensitivity_results.csv"),
        }

        # Set the global paths for the CSV files containing the test results for avalanche effect, key sensitivity, and stability used to the createLeaderBoard function.
        createLeaderBoard.__globals__["AV_FILE"] = os.path.join(
            phase_dir, "avalancheEffect_results.csv"
        )
        createLeaderBoard.__globals__["KS_FILE"] = os.path.join(
            phase_dir, "keySensitivity_results.csv"
        )
        createLeaderBoard.__globals__["STABILITY_FILE"] = os.path.join(
            phase_dir, "stability_results.csv"
        )

        # counter for the number of (alfa, beta) pairs processed and the total number of pairs to be processed across all maps.
        pair_number = 0
        total_pairs = sum(len(pairs) for pairs in pairs_by_map.values())

        # Iterate over each map and its corresponding pairs of (alfa, beta) to run the tests.
        for map_name, pairs in pairs_by_map.items():
            for alpha, beta_value in pairs:
                pair_number += 1
                print(
                    f"Running phase {phase_number} pair "
                    f"{pair_number}/{total_pairs}: map={map_name}, "
                    f"alfa={alpha}, beta={beta_value}"
                )

                # retrieve the stability data for the current map and (alfa, beta) pair using the measure_stability function.
                stability_data = measure_stability(map_name, alpha, beta_value)

                # extract the delta value from the stability data and run both the avalanche effect and key sensitivity tests for the current map and (alfa, beta) pair using the run_test function.
                delta = float(stability_data[3])

                # Run the avalanche effect test for the current map and (alfa, beta) pair using the run_test function.
                run_test(
                    TestType.AVALANCHE_EFFECT, alpha, beta_value, delta,
                    tests_number, stability_data, map_name
                )
                run_test(
                    TestType.KEY_SENSITIVITY, alpha, beta_value, delta,
                    tests_number, stability_data, map_name
                )
        return phase_dir

    # Phase 1 clears previous builds, compiles the code, and runs the screening tests for all maps and parameter pairs.
    if phase in ("1", "all"):
        subprocess.run(["make", "clear"], cwd=current_dir, check=True)
        subprocess.run(["make", "build"], cwd=current_dir, check=True)

        # Clear the results of phase 1 before running new tests.
        clear_phase_results(1)

        # Get the pairs of (alfa, beta) for each map to be tested in phase 1.
        phase_one_pairs = {
            map_name: [
                (alpha, beta_value)
                for alpha in alfa
                for beta_value in beta
            ]
            for map_name in maps
        }

        # Execute phase 1 tests for all maps and parameter pairs.
        execute_phase(1, phase_one_pairs, args.tests or SCREENING_TESTS)

        # After running phase 1 tests, create plots and generate the leaderboard for the results.
        createPlots(output_dir=Path(RESULTS_DIR) / "phase_1" / "plots")
        createLeaderBoard(
            output_path=os.path.join(RESULTS_DIR, "phase_1",
                                     "ranking_alfa_beta.csv")
        )

    # Phase 2 uses the ranking from phase 1 to select the top N pairs of (alfa, beta) for each map and runs the confirmation tests.
    if phase in ("2", "all"):
        subprocess.run(["make", "build"], cwd=current_dir, check=True)

        # Clear the results of phase 2 before running new tests.
        clear_phase_results(2)

        # Determine the ranking CSV file to use for phase 2 tests, either the default ranking CSV or a user-specified one.
        ranking_path = args.ranking

        # Load the top N pairs of (alfa, beta) for each map from the ranking CSV file to be used in phase 2 tests.
        if args.ranking == RANKING_CSV:
            ranking_path = os.path.join(RESULTS_DIR, "phase_1",
                                        "ranking_alfa_beta.csv")
        phase_two_pairs = load_phase_two_pairs(ranking_path, args.top)

        # Execute phase 2 tests for the selected top N pairs of (alfa, beta) for each map.
        execute_phase(2, phase_two_pairs, args.tests or CONFIRMATION_TESTS)
        createLeaderBoard(
            output_path=os.path.join(RESULTS_DIR, "phase_2",
                                     "ranking_alfa_beta.csv")
        )


if __name__ == "__main__":
    main()

    # After running all tests, create the plots
    createPlots()

    # After running all tests, create the leaderboard
    createLeaderBoard()