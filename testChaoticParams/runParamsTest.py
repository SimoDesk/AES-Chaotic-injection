# Define a function to calculate the avalanche effect between two ciphertext files
def calcola_hamming(file_c1, file_c2):
    # store in two variables the bytes read from the two ciphertext files, which are opened in binary mode
    with open(file_c1, 'rb') as f1, open(file_c2, 'rb') as f2:
        c1_bytes = f1.read()
        c2_bytes = f2.read()

    # Calculate the Hamming distance between the two ciphertexts by counting the number of differing bits
    distanza_hamming = sum(bin(b1 ^ b2).count('1') for b1, b2 in zip(c1_bytes, c2_bytes))

    # Calculate the percentage of differing bits relative to the total number of bits (128 bits for AES)
    percentuale = (distanza_hamming / 128.0) * 100
    
    return distanza_hamming, percentuale


# Define a function to run the key sensitivity test
def run_key_sensitivity(plaintext_hex, iv_hex, key_hex, map, alfa, beta, delta):

    # Define the path to the test_avalanche executable
    executable_path = os.path.join(current_dir, "test_params")

    # Use a temporary directory to store the ciphertext files generated during the test
    with tempfile.TemporaryDirectory(dir="/dev/shm") as temp_dir:

        # Run the test_avalanche executable with the original plaintext
        subprocess.run([executable_path, map, plaintext_hex, iv_hex, key_hex, str(0), str(alfa), str(beta), str(delta)], capture_output=True, text=True, cwd=temp_dir, check=True)

        # transform the key hex string into a bytearray to flip a random bit
        byte_array = bytearray(bytes.fromhex(key_hex))

        # select a random byte and a random bit within that byte to flip
        random_byte_id = random.randint(0, len(byte_array) - 1)
        random_bit_id = random.randint(0, 7)

        # flip the selected bit in the selected byte by using XOR operation 
        byte_array[random_byte_id] ^= (1 << random_bit_id)

        # convert the modified bytearray back to a hex string
        modified_key_hex = byte_array.hex()

        # Run the test_avalanche executable with the modified key
        subprocess.run([executable_path, map, plaintext_hex, iv_hex, modified_key_hex, str(1), str(alfa), str(beta), str(delta)], capture_output=True, text=True, cwd=temp_dir, check=True)

        # Calculate the avalanche effect between the two ciphertexts generated by the original and modified plaintexts
        file_c1 = os.path.join(temp_dir, "cipher_0.bin")
        file_c2 = os.path.join(temp_dir, "cipher_1.bin")
        distanza_hamming, percentuale = calcola_hamming(file_c1, file_c2)

    return distanza_hamming, percentuale


